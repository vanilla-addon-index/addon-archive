local function addPhrase(value)
    value=string.gsub(value or "", "^%s+", "")
    value=string.gsub(value, "%s+$", "")
    if value=="" then return end
    value=string.sub(value,1,70)
    local tab=currentTab()
    local arr=tab.phrases
    if table.getn(arr)>=60 then
        S.phraseStatus:SetText("Up to 60 phrases per tab.")
        return
    end
    local i
    for i=1,table.getn(arr) do
        if string.lower(arr[i])==string.lower(value) then
            S.phraseStatus:SetText("Already listed."); return
        end
    end
    table.insert(arr,value)
    phrasePage=math.max(1,math.ceil(table.getn(arr)/FILTER_ROWS))
    if S.phraseInput then S.phraseInput:SetText(""); S.phraseInput:ClearFocus() end
    S.phraseStatus:SetText("Phrase added for this tab.")
    updatePhraseRows(); updateAll(true,true)
end


local function inputPosition()
    if not editBox or not root then return end
    local anchor=(MCWindows and MCWindows.GetInputAnchor()) or root
    local bottom=anchor:GetBottom() or cfg.y
    -- 1.12 has one global ChatFrameEditBox, parented to UIParent. Do not hide
    -- it, replace its scripts, or create a second text entry control.
    local above = bottom < 41
    local point = above and "BOTTOMLEFT" or "TOPLEFT"
    local relative = above and "TOPLEFT" or "BOTTOMLEFT"
    local offset = above and 5 or -3
    local p,rel,relpoint,x,y=editBox:GetPoint(1)
    if p~=point or rel~=anchor or relpoint~=relative or x~=0 or y~=offset then
        editBox:ClearAllPoints()
        editBox:SetPoint(point,anchor,relative,0,offset)
    end
    editBox:SetWidth(anchor:GetWidth() or cfg.width)
end

local function parkNative(frame)

local function categoryList()
    local rows={}
    local i
    for i=1,table.getn(baseCategories) do
        table.insert(rows, {key=baseCategories[i][1],name=baseCategories[i][2]})
    end
    local extra={}
    for key,name in pairs(store.channels) do
        table.insert(extra,{key=key,name="# "..name})
    end
    table.sort(extra,function(a,b) return a.name<b.name end)
    for i=1,table.getn(extra) do table.insert(rows,extra[i]) end
    return rows
end

local function refreshSettingsRows()
    if not initialized or not S.settingsFrame then return end
    local tab=currentTab()
    local rows=categoryList()
    local pageCount=math.max(1,math.ceil(table.getn(rows)/PAGE_ROWS))
    channelPage=clamp(channelPage,1,pageCount)
    if S.channelPageText then
        S.channelPageText:SetText("Page "..channelPage.." / "..pageCount)
    end
    local i,entry,widgets,enabled,color
    for i=1,PAGE_ROWS do
        entry=rows[(channelPage-1)*PAGE_ROWS+i]
        widgets=S.settingsRows[i]
        if entry then
            widgets.key=entry.key
            widgets.name:SetText(entry.name)
            enabled=tab.enabled[entry.key]
            if enabled==nil then enabled=tab.defaultOn end
            widgets.toggleText:SetText(enabled and "ON" or "OFF")
            widgets.toggleText:SetTextColor(enabled and 0.54 or 0.96,enabled and 0.89 or 0.57,0.61)
            local r,g,b=effectiveColor(tab,entry.key,nil,nil)
            -- A named channel inherits its generic CHANNEL color if not overridden.
            if string.sub(entry.key,1,8)=="CHANNEL:" then
                r,g,b=effectiveColor(tab,"CHANNEL",entry.key,nil)
            end
            widgets.swatch:SetVertexColor(r,g,b)
            widgets.toggle:Show(); widgets.color:Show(); widgets.name:Show()
        else
            widgets.key=nil
            widgets.toggle:Hide(); widgets.color:Hide(); widgets.name:Hide()
        end
    end
    if fontLabel then fontLabel:SetText("FONT "..(tab.font or cfg.defaultFont)) end
    refreshButtons()
end


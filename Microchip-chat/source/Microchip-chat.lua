-- Dedicated history page: per-channel limits are shared across tabs because
-- messages are recorded once, then filtered into different tab views.
local function historyRowsRefresh()
    if not S.historyPane then return end
    local entries=categoryList()
    local pages=math.max(1,math.ceil(table.getn(entries)/HISTORY_ROWS))
    historyPage=clamp(historyPage,1,pages)
    S.historyPageLabel:SetText("Page "..historyPage.." / "..pages)
    if not S.historyDefaultInput:HasFocus() then
        S.historyDefaultInput:SetText(tostring(cfg.history))
    end
    local i,entry,row,key,count,limit
    for i=1,HISTORY_ROWS do
        entry=entries[(historyPage-1)*HISTORY_ROWS+i]
        row=S.historyRows[i]
        if entry then
            key=entry.key
            row.key=key
            if key=="CHANNEL" then
                row.name:SetText("Numbered channels (default)")
            else
                row.name:SetText(entry.name)
            end
            count=MCHistory.Count(store,key)
            row.count:SetText(tostring(count).." saved")
            limit=MCHistory.Limit(store,cfg.history,key)
            if not row.input:HasFocus() then row.input:SetText(tostring(limit)) end
            row.name:Show();row.count:Show();row.input:Show()
            row.apply:Show();row.reset:Show()
            -- SetEnabled was added after vanilla WoW 1.12. Use the older
            -- Button:Enable()/Disable() methods to keep settings loadable.
            if store.historyLimits[key]~=nil then
                row.reset:Enable()
            else
                row.reset:Disable()
            end
        else
            row.key=nil
            row.name:Hide();row.count:Hide();row.input:Hide()
            row.apply:Hide();row.reset:Hide()
        end
    end
end

local function saveHistoryLimit(key,box)
    local n=tonumber(box:GetText() or "")
    if not n or n~=math.floor(n) or n<50 or n>MAX_HISTORY then
        S.historyStatus:SetText("Enter a whole number from 50 to 5000.")
        S.historyStatus:SetTextColor(1,0.62,0.54)
        box:ClearFocus()
        return
    end
    if key then
        MCHistory.SetLimit(store,cfg.history,key,n)
    else
        cfg.history=n
        MCHistory.Trim(store,cfg.history)
    end
    box:ClearFocus()
    S.historyStatus:SetText("Saved. Limits apply to future messages; deleted history cannot be recovered.")
    S.historyStatus:SetTextColor(0.67,0.96,0.76)
    updateAll(false,true)
    historyRowsRefresh()
end

-- This operation deliberately does not call notify(): a status chat message
-- would immediately recreate history after it was cleared.
local function clearAllHistory()
    if not MCHistory or not store then return end
    MCHistory.Clear(store)
    recent={}
    combatRecent={}
    historyView={rows={},older=false,newer=false}
    if liveFrame then liveFrame:Clear() end
    if logFrame then logFrame:Clear() end
    if MCWindows and MCWindows.ClearHistory then MCWindows.ClearHistory() end
    if historyCount then historyCount:SetText("0 saved across channels") end
    if S.historyStatus then
        S.historyStatus:SetText("All saved chat and combat history cleared.")
        S.historyStatus:SetTextColor(0.67,0.96,0.76)
    end
    historyRowsRefresh()
end


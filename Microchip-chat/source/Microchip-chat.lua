-- Mouse-wheel history paging. Only a short window is rendered; reaching
-- either edge loads the adjacent overlapping page on demand.
local function scrollChatByWheel(delta)
    delta=tonumber(delta) or 0
    if delta>0 then
        if not expanded then setExpanded(true) end
        if logFrame:AtTop() and historyView.older then
            historyShift("older")
        end
        local i
        for i=1,3 do logFrame:ScrollUp() end
    elseif delta<0 then
        if expanded then
            if logFrame:AtBottom() and historyView.newer then
                historyShift("newer")
            end
            local i
            for i=1,3 do logFrame:ScrollDown() end
        else
            liveFrame:ScrollToBottom()
        end
    end
end


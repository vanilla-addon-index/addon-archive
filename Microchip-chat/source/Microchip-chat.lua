local function clamp(v, lo, hi)
    v = tonumber(v) or lo
    if v < lo then v = lo end
    if v > hi then v = hi end
    return math.floor(v)
end

local function copyColor(c)
    if type(c) ~= "table" then return nil end
    return {clamp((c[1] or 0.8) * 255, 0, 255)/255,
            clamp((c[2] or 0.8) * 255, 0, 255)/255,
            clamp((c[3] or 0.8) * 255, 0, 255)/255}
end

local function colorHex(r,g,b)
    return string.format("%02x%02x%02x", clamp((r or 1)*255,0,255),
        clamp((g or 1)*255,0,255), clamp((b or 1)*255,0,255))
end


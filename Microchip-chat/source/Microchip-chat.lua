local function applyTheme()
    local i,record,r,g,b,region
    for i=1,table.getn(U.surfaces) do
        record=U.surfaces[i]
        r,g,b=palette(record.role)
        local a=record.alpha
        if record.texture==rootSurface then a=expanded and 0.92 or 0.18 end
        record.texture:SetVertexColor(colorLimit(r+record.offset[1]),
            colorLimit(g+record.offset[2]),colorLimit(b+record.offset[3]),a)
    end
    for i=1,table.getn(U.buttons) do

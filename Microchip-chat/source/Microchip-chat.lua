local function channelKey(name)
    if type(name) ~= "string" then return nil end
    name = string.gsub(name, "^%d+%.%s*", "")
    name = string.gsub(name, "%s+%-%s+.*$", "")
    name = string.gsub(name, "^%s+", "")
    name = string.gsub(name, "%s+$", "")
    if name == "" then return nil end
    return "CHANNEL:" .. string.lower(name), name
end

local function noteChannel(name)
    local key, pretty = channelKey(name)
    if not key then return end
    if not store.channels[key] then store.channels[key] = pretty end
end


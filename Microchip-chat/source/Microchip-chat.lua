SlashCmdList["MICROCHIPCHAT"]=function(input)
    if not initialized then return end
    local _,_,cmd,value=string.find(input or "","^%s*(%S*)%s*(.-)%s*$")
    cmd=string.lower(cmd or "")
    value=value or ""
    local lower=string.lower(value)
    local n=tonumber(value)
    if cmd=="" or cmd=="history" or cmd=="toggle" then
        MicrochipChat_ToggleHistory()
    elseif cmd=="options" or cmd=="settings" then
        MicrochipChat_ToggleSettings()
    elseif cmd=="lock" then
        cfg.locked=not cfg.locked; refreshButtons()
        if MCWindows then MCWindows.Refresh() end
    elseif cmd=="blizzard" then
        if lower=="off" then cfg.hideBlizzard=true; suppressNative()
        elseif lower=="on" then cfg.hideBlizzard=false; showNative()
        else printHelp() end
    elseif cmd=="tab" then
        local _,_,sub,rest=string.find(value,"^%s*(%S+)%s*(.-)%s*$")
        sub=string.lower(sub or "")
        if sub=="add" then addTab(rest)
        elseif sub=="remove" then removeTab()
        elseif sub=="rename" then renameTab(rest)
        elseif sub=="select" then selectTab(tonumber(rest) or 1)
        else printHelp() end
    elseif cmd=="window" or cmd=="detach" or cmd=="dock" then
        local operation,index
        if cmd=="window" then
            local _,_,sub,rest=string.find(value,"^%s*(%S+)%s*(.-)%s*$")
            operation=string.lower(sub or "")
            index=tonumber(rest) or cfg.selected
        else
            operation=cmd
            index=n or cfg.selected
        end
        local tab=store.tabs[index]
        if not tab then notify("No tab at that number.")
        elseif operation=="detach" then
            if MCWindows.Detach(tab) then
                if cfg.selected==index then
                    local i
                    for i=1,table.getn(store.tabs) do
                        if not store.tabs[i].detached then selectTab(i);break end
                    end
                end
                updateAll(true,true)
            else notify("Keep at least one main-window tab; add another tab first.") end
        elseif operation=="dock" then MCWindows.Dock(tab);updateAll(true,true)
        else printHelp() end
    elseif cmd=="filter" then
        local _,_,sub,rest=string.find(value,"^%s*(%S+)%s*(.-)%s*$")
        sub=string.lower(sub or "")
        local tab=currentTab()
        if sub=="add" then addPhrase(rest)
        elseif sub=="remove" then
            local index=tonumber(rest)
            if index and tab.phrases[index] then
                table.remove(tab.phrases,index); updateAll(true,true)
                if settingsOpen then updatePhraseRows() end
            end
        elseif sub=="world" then tab.useWCF=(string.lower(rest)=="on"); updateAll(true,true)
        elseif sub=="scope" then tab.worldOnly=(string.lower(rest)~="all"); updateAll(true,true)
        else printHelp() end
    elseif cmd=="lines" and n then
        cfg.visible=clamp(n,1,15); updateAll(true,false)
    elseif cmd=="font" and n then
        currentTab().font=clamp(n,9,20); updateAll(true,true)
    elseif cmd=="defaultfont" then
        if not U.setDefaultFont(n) then
            notify("Default font size must be a whole number from 9 to 20.")
        else
            notify("Default font size set to "..cfg.defaultFont.." pt for all tabs.")
        end
    elseif (cmd=="limit" or cmd=="historysize") and n then
        cfg.history=clamp(n,50,MAX_HISTORY); ensureEntrySize(); updateAll(false,true)
    elseif cmd=="controls" and n then
        cfg.controlsHold=clamp(n,0,30);refreshButtons()
    elseif cmd=="width" and n then
        cfg.width=clamp(n,520,900); updateAll(false,false)
    elseif cmd=="hold" and n then
        cfg.hold=clamp(n,1,120); updateAll(true,false)
    elseif cmd=="fade" and n then
        cfg.fade=clamp(n,1,15); updateAll(true,false)
    elseif cmd=="fading" then
        if lower=="on" then cfg.fading=true
        elseif lower=="off" then cfg.fading=false
        else printHelp(); return end
        updateAll(true,false)
    elseif cmd=="classcolors" then
        if lower=="on" then cfg.classColors=true
        elseif lower=="off" then cfg.classColors=false
        else printHelp(); return end
        updateAll(true,true)
    elseif cmd=="height" and n then
        if n==0 then cfg.heightCap=0 else cfg.heightCap=clamp(n,400,1200) end
        updateAll(false,false)
    elseif cmd=="clock" then
        if lower=="12" or lower=="24" or lower=="seconds" then cfg.clock=lower
        else printHelp() end
    elseif cmd=="stamp" then
        if lower=="on" then cfg.timestamps=true
        elseif lower=="off" then cfg.timestamps=false
        else printHelp() end
    elseif cmd=="reset" then
        cfg.x=defaults.x; cfg.y=defaults.y
        cfg.width=defaults.width;cfg.compactHeight=0;cfg.heightCap=0
        root:ClearAllPoints()
        root:SetPoint("BOTTOMLEFT",UIParent,"BOTTOMLEFT",cfg.x,cfg.y)
        updateSize()
    elseif cmd=="demo" then
        append("GUILD","The new message appears at the bottom.","Guildmate")
        append("PARTY","Tabs have independent channel filters and colors.","Healer")
        append("CHANNEL","History is inside this same window.","Player","1. General - Stormwind City",1)
        append("WHISPER","Press Enter; chat input follows the dock.","Friend")
        append("COMBAT","Your Shadow Bolt hits a target for 432 Shadow damage.",nil,nil,nil,nil,nil,nil,"CHAT_MSG_SPELL_SELF_DAMAGE")
        append("COMBAT","Enemy hits you for 210.",nil,nil,nil,nil,nil,nil,"CHAT_MSG_COMBAT_CREATURE_VS_SELF_HITS")
        if settingsOpen then refreshSettingsRows() end
    elseif cmd=="help" then printHelp()
    else printHelp() end
end



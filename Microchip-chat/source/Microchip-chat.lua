-- On a true 1.12 client alpha may not propagate from a frame to all
-- children (that behavior changed in patch 2.1). Cache every toolbar region
-- so alpha 0 also hides the labels, button fills and highlights.
local function collectControlVisuals(frame)
    table.insert(controlVisuals,frame)
    if frame.GetRegions then
        local regions={frame:GetRegions()}
        local i
        for i=1,table.getn(regions) do
            if regions[i] then table.insert(controlVisuals,regions[i]) end
        end
    end
    if frame.GetChildren then
        local children={frame:GetChildren()}
        local i
        for i=1,table.getn(children) do
            if children[i] then collectControlVisuals(children[i]) end
        end
    end
end


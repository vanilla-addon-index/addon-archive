local function isEnabled(tab, kind, channel)
    if kind == "LEGACY" then return true end
    local allowed
    if kind == "CHANNEL" and channel then allowed = tab.enabled[channel] end
    if allowed == nil then allowed = tab.enabled[kind] end
    if allowed == nil then allowed = tab.defaultOn end
    return allowed == true
end

local function effectiveColor(tab, kind, channel, channelNumber)
    local chosen = (channel and tab.colors[channel]) or tab.colors[kind]
    if type(chosen) == "table" then
        return chosen[1] or 0.9, chosen[2] or 0.9, chosen[3] or 0.9
    end
    local info = ChatTypeInfo and ChatTypeInfo[kind]
    if kind == "CHANNEL" and ChatTypeInfo and channelNumber then
        info = ChatTypeInfo["CHANNEL" .. tostring(channelNumber)] or info
    end
    if not info and kind == "WHISPER_INFORM" and ChatTypeInfo then
        info = ChatTypeInfo.WHISPER
    end
    if kind == "COMBAT" and not info then return 0.92,0.84,0.72 end
    if info and info.r then return info.r, info.g, info.b end
    if kind == "SYSTEM" then return 1.0, 0.8, 0.35 end
    return 0.85, 0.88, 0.93
end

local function stamp()
    if not cfg.timestamps then return "" end
    if cfg.clock == "seconds" then return date("%H:%M:%S") end
    if cfg.clock == "12" then return date("%I:%M %p") end
    return date("%H:%M")
end

-- Preserve incoming WoW |Hitem:...|h links verbatim.  Only the author gets
-- an additional native player hyperlink; SetItemRef handles left/right clicks.
local function playerLink(author)
    if type(author)~="string" or author=="" then return "" end
    if string.find(author,"[|:%c%[%]]") then return author end
    if MCClassColors then return MCClassColors.Link(author,cfg.classColors) end
    return "|cffd4dde5|Hplayer:"..author.."|h["..author.."]|h|r"
end

local function isWorld(record)
    if record.kind~="CHANNEL" then return false end
    return record.channel=="CHANNEL:world"
end

local function visiblePlainText(text)
    local v=string.lower(text or "")
    v=string.gsub(v,"|c%x%x%x%x%x%x%x%x","")
    v=string.gsub(v,"|H[^|]-|h","")
    v=string.gsub(v,"|h","")
    v=string.gsub(v,"|r","")
    return v
end

local function passesTabFilter(tab,record)
    if record.force then return true end
    if record.legacy then return true end
    if not tab then return false end
    if not isEnabled(tab,record.kind,record.channel) then return false end
    -- Built-in World filter, with independent per-tab sensitivity/categories.
    if isWorld(record) and MCWorldFilter and
       MCWorldFilter.ShouldHide(record.adCategory,record.adScore,tab) then return false end
    if tab.filterEnabled==false then return true end
    if tab.worldOnly~=false and not isWorld(record) then return true end
    local plain=visiblePlainText(record.msg)
    local phrases=tab.phrases or {}
    local i
    for i=1,table.getn(phrases) do
        local term=string.lower(phrases[i])
        if term~="" and string.find(plain,term,1,true) then return false end
    end
    return true
end

local function activeChannelCount(tab)

    return 0
end

local function renderRecord(tab, record)
    if record.legacy then
        return (MCURLs and MCURLs.Linkify(record.text or "")) or (record.text or ""), record.r or 0.9, record.g or 0.9, record.b or 0.9
    end
    local r,g,b = effectiveColor(tab, record.kind, record.channel, record.channelNumber)
    local prefix = ""
    if record.stamp and record.stamp ~= "" then
        prefix = "|cff8d9ca5[" .. record.stamp .. "]|r "
    end
    local label = labels[record.kind] or record.kind or "Chat"
    if record.kind == "COMBAT" then
        return prefix .. (MCURLs and MCURLs.Linkify(record.msg or "") or (record.msg or "")),r,g,b
    end
    if record.kind == "CHANNEL" then
        label = store.channels[record.channel] or "Channel"
        -- The real in-game channel index can vary by character and by session.
        if record.channel=="CHANNEL:world" and
           tonumber(record.channelNumber) and tonumber(record.channelNumber)>0 then
            label = tostring(record.channelNumber) .. ". " .. label
        end
    end
    if string.len(label) > 25 then label = string.sub(label, 1, 25) end
    prefix = prefix .. "|cffd3aa68[" .. label .. "]|r "
    if record.author and record.author ~= "" and
       record.kind ~= "SYSTEM" and record.kind ~= "LOOT" and record.kind ~= "MONEY" then
        prefix = prefix .. playerLink(record.author) .. ": "
    end
    return prefix .. (MCURLs and MCURLs.Linkify(record.msg or "") or (record.msg or "")), r,g,b
end

-- WoW 1.12 combat events are pre-formatted English chat strings. Events
-- explicitly targeting SELF are reliable; shared combat events need a small
-- victim-oriented text check. Do not treat "Your Fireball hits X" as damage
-- received. Old saved records without an event remain in All Events.
local incomingCombatEvents = {
    CHAT_MSG_COMBAT_CREATURE_VS_SELF_HITS=true,
    CHAT_MSG_COMBAT_CREATURE_VS_SELF_MISSES=true,
    CHAT_MSG_SPELL_CREATURE_VS_SELF_BUFF=true,
    CHAT_MSG_SPELL_CREATURE_VS_SELF_DAMAGE=true,
    CHAT_MSG_SPELL_PERIODIC_SELF_BUFFS=true,
    CHAT_MSG_SPELL_PERIODIC_SELF_DAMAGE=true,
    CHAT_MSG_SPELL_AURA_GONE_SELF=true,
    CHAT_MSG_SPELL_DAMAGESHIELDS_ON_SELF=true
}
local function isAboutPlayer(record)
    if record.kind~="COMBAT" then return false end
    if incomingCombatEvents[record.combatEvent] then return true end
    local msg=string.lower(record.msg or "")
    -- Source/target ambiguity is intentional here: prefer missing an
    -- unusual locale-specific line to showing everyone else's combat.
    if string.find(msg,"^you ") then
        for _,verb in ipairs({"suffer", "gain", "lose", "are ", "were ",
                              "resist", "dodge", "parry", "block", "absorb",
                              "die", "fall", "take ", "have been"}) do
            if string.find(msg,"^you "..verb,1,true) then return true end
        end
    end
    for _,fragment in ipairs({" hits you", " crits you", " misses you",
             " heals you", " affects you", " on you", " to you",
             " is absorbed by you", " was resisted by you"}) do
        if string.find(msg,fragment,1,true) then return true end
    end
    local name=UnitName and UnitName("player")
    if name and name~="" then
        local target=string.lower(name)
        -- Only consider the player's name in target position; the player
        -- casting a spell on someone else does not count as incoming.
        for _,verb in ipairs({" hits ", " crits ", " heals ", " misses ",
                              " on ", " to "}) do
            if string.find(msg,verb..target,1,true) then return true end
        end
        for _,verb in ipairs({" suffers ", " gains ", " loses ",
                              " is afflicted", " dies"}) do
            if string.find(msg,target..verb,1,true) then return true end
        end
    end
    return false
end

local function matches(tab, record)
    if not passesTabFilter(tab,record) then return false end
    if tab.isCombatTab and tab.combatView=="me" then
        return isAboutPlayer(record)
    end
    return true
end

-- Combat keeps a separate rolling buffer so spammy fights do not push
-- unrelated chat lines out of live view or persistent chat history.
-- A tab showing both kinds receives them in original arrival order.
local function recordsForTab(chatRecords,combatRecords,tab)
    if not isEnabled(tab,"COMBAT") then return chatRecords end
    local all={}
    local i
    for i=1,table.getn(chatRecords) do table.insert(all,chatRecords[i]) end
    for i=1,table.getn(combatRecords) do table.insert(all,combatRecords[i]) end
    table.sort(all,function(a,b) return (a.sequence or 0)<(b.sequence or 0) end)
    return all
end

local function paintLive()
    if not initialized then return end
    local tab = currentTab()
    liveFrame:Clear()
    liveFrame:SetMaxLines(cfg.visible)
    local i
    -- Rebuild from a small rolling buffer. This restarts fade for visible lines
    -- only when the user explicitly changes tabs or font/settings.
    local lines=recordsForTab(recent,combatRecent,tab)
    for i=1,table.getn(lines) do
        local r = lines[i]
        if matches(tab,r) and (not cfg.fading or (GetTime() - (r.entered or 0)) < cfg.hold+cfg.fade) then
            local text,red,green,blue=renderRecord(tab,r)
            liveFrame:AddMessage(text,red,green,blue)
        end
    end
end

-- Render only a small window of history. Saved per-channel buffers retain
-- thousands of records, but the native ScrollingMessageFrame never receives
-- more than HISTORY_PAGE_SIZE messages at once.
local function historyBucketEnabled(key)
    local tab=currentTab()
    if key=="LEGACY" then return true end
    if string.sub(key,1,8)=="CHANNEL:" then
        return isEnabled(tab,"CHANNEL",key)
    end
    return isEnabled(tab,key)
end

local function historyFetch(direction,pivot,count)
    local tab=currentTab()
    return MCHistory.Window(store,direction,pivot,count,historyBucketEnabled,
        function(record) return matches(tab,record) end)
end

local function historyRender()
    if not logFrame then return end
    logFrame:Clear()
    local i,record,text,r,g,b
    for i=1,table.getn(historyView.rows) do
        record=historyView.rows[i]
        text,r,g,b=renderRecord(currentTab(),record)
        logFrame:AddMessage(text,r,g,b)
    end
    if historyCount then
        historyCount:SetText(table.getn(historyView.rows).." loaded / "..
            MCHistory.Count(store).." saved")
    end
end

local function historyJump(edge)
    if not initialized then return end
    local rows,more
    if edge=="top" then
        rows,more=historyFetch("newer",nil,HISTORY_PAGE_SIZE)
        historyView.rows=rows;historyView.older=false;historyView.newer=more
        historyRender()
        logFrame:ScrollToTop()
    else
        rows,more=historyFetch("older",nil,HISTORY_PAGE_SIZE)
        historyView.rows=rows;historyView.older=more;historyView.newer=false
        historyRender()
        logFrame:ScrollToBottom()
    end
end

-- Overlapping pages maintain scrolling continuity without an enormous chat
-- frame. Only HISTORY_PAGE_STEP additional records are fetched at a boundary.
local function historyShift(direction)
    local rows=historyView.rows
    local count=table.getn(rows)
    if count==0 then return end
    local added,more,combined,i,start,overlap
    if direction=="older" then
        if not historyView.older then return end
        added,more=historyFetch("older",rows[1].sequence,HISTORY_PAGE_STEP)
        if table.getn(added)==0 then historyView.older=false;return end
        combined={}
        for i=1,table.getn(added) do table.insert(combined,added[i]) end
        overlap=HISTORY_PAGE_SIZE-table.getn(added)
        for i=1,math.min(count,overlap) do table.insert(combined,rows[i]) end
        historyView.older=more
        historyView.newer=historyView.newer or count>overlap
        historyView.rows=combined
        historyRender()
        logFrame:ScrollToTop()
        -- Move back to the former first message; the next wheel movement
        -- exposes the newly loaded older records.
        for i=1,table.getn(added) do logFrame:ScrollDown() end
    else
        if not historyView.newer then return end
        added,more=historyFetch("newer",rows[count].sequence,HISTORY_PAGE_STEP)
        if table.getn(added)==0 then historyView.newer=false;return end
        overlap=HISTORY_PAGE_SIZE-table.getn(added)
        start=math.max(1,count-overlap+1)
        combined={}
        for i=start,count do table.insert(combined,rows[i]) end
        for i=1,table.getn(added) do table.insert(combined,added[i]) end
        historyView.older=historyView.older or start>1
        historyView.newer=more
        historyView.rows=combined
        historyRender()
        logFrame:ScrollToBottom()
        for i=1,table.getn(added) do logFrame:ScrollUp() end
    end
end

local function paintHistory()
    -- Never build the history frame while compact chat is in use.
    if not initialized or not expanded then return end
    historyJump("bottom")
end

-- A surface retains its original light/dark offset from the chosen global
-- background color. The live chat alpha remains independent of the RGB theme.
local function surface(parent, alpha, red, green, blue, role)
    role=role or "window"
    local t=parent:CreateTexture(nil,"BACKGROUND")
    t:SetTexture("Interface\\Tooltips\\UI-Tooltip-Background")
    local baseline=paletteDefaults[role]
    local r,g,b=palette(role)
    local offset={ (red or baseline[1])-baseline[1],
                   (green or baseline[2])-baseline[2],
                   (blue or baseline[3])-baseline[3] }
    t:SetVertexColor(colorLimit(r+offset[1]),colorLimit(g+offset[2]),colorLimit(b+offset[3]),alpha)
    t:SetAllPoints(parent)
    table.insert(U.surfaces,{texture=t,role=role,offset=offset,alpha=alpha})
    return t
end


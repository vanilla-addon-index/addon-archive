local function append(kind, msg, author, channelName, channelNumber, force, decoratedName, zoneID, combatEvent)
    if type(msg)~="string" or msg=="" then return end
    local key
    if kind=="CHANNEL" then
        key=channelKey(channelName)
        if key then noteChannel(channelName) end
    end
    -- arg8 is the channel index in vanilla 1.12; older client forks may
    -- provide it only as the leading number in arg4 (decoratedName).
    if kind=="CHANNEL" and (not channelNumber or channelNumber<1) then
        local _,_,parsed=string.find(decoratedName or "","^%s*(%d+)%.")
        channelNumber=tonumber(parsed)
    end
    store.nextSequence=(store.nextSequence or 0)+1
    local record={kind=kind,msg=msg,author=author,channel=key,
        channelNumber=channelNumber,stamp=stamp(),entered=GetTime(),force=force,
        sequence=store.nextSequence,combatEvent=combatEvent}
    if key=="CHANNEL:world" and MCWorldFilter then
        record.adCategory,record.adScore=MCWorldFilter.Classify(msg,author or "")
    end
    MCHistory.Add(store,cfg.history,record)
    if kind=="COMBAT" then
        table.insert(combatRecent,record)
        while table.getn(combatRecent)>65 do table.remove(combatRecent,1) end
    else
        table.insert(recent,record)
        while table.getn(recent)>65 do table.remove(recent,1) end
    end
    local tab=currentTab()
    if matches(tab,record) and not (MCWindows and MCWindows.IsDetached(tab)) then
        local rendered,r,g,b=renderRecord(tab,record)
        liveFrame:AddMessage(rendered,r,g,b)
        -- While reading older history, keep the current page stationary.
        -- New messages remain in the saved buffers and appear on BOTTOM.
        if expanded then
            if not historyView.newer and logFrame:AtBottom() then
                table.insert(historyView.rows,record)
                if table.getn(historyView.rows)>HISTORY_PAGE_SIZE then
                    table.remove(historyView.rows,1)
                    historyView.older=true
                end
                logFrame:AddMessage(rendered,r,g,b)
            else
                -- The reader is looking at a previous point in history.
                -- Mark newer records available without shifting their view.
                historyView.newer=true
            end
        end
    end
    if MCWindows then MCWindows.Message(record) end
    if historyCount then
        historyCount:SetText(MCHistory.Count(store) .. " saved across channels")
    end
end


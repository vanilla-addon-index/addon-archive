local function startup()
    if initialized then return end
    if type(OctoStreamChatDB)~="table" then OctoStreamChatDB={} end
    store=OctoStreamChatDB
    if type(store.entries)~="table" then store.entries={} end
    if type(store.combatEntries)~="table" then store.combatEntries={} end
    -- Give previous-version chat records stable ordering before the first
    -- recorded combat message. This preserves saved history on upgrade.
    local seq=tonumber(store.nextSequence) or 0
    local j
    for j=1,table.getn(store.entries) do
        if type(store.entries[j])=="table" then
            if not store.entries[j].sequence then
                seq=seq+1; store.entries[j].sequence=seq
            elseif store.entries[j].sequence>seq then seq=store.entries[j].sequence end
        end
    end
    for j=1,table.getn(store.combatEntries) do
        if type(store.combatEntries[j])=="table" then
            if not store.combatEntries[j].sequence then
                seq=seq+1; store.combatEntries[j].sequence=seq
            elseif store.combatEntries[j].sequence>seq then
                seq=store.combatEntries[j].sequence
            end
        end
    end
    store.nextSequence=seq
    if type(store.settings)~="table" then store.settings={} end
    if type(store.channels)~="table" then store.channels={} end
    if type(store.tabs)~="table" or table.getn(store.tabs)==0 then
        store.tabs=makeDefaultTabs()
    elseif not store.migrated04 then
        -- Upgrade the untouched stock "All" tab, but do not overwrite
        -- user-customized channel selections or remove their other tabs.
        local old=store.tabs[1]
        if old and old.name=="All" and old.defaultOn==true and
           type(old.enabled)=="table" and next(old.enabled)==nil then
            old.name="General";old.defaultOn=false
            old.enabled={["CHANNEL:general"]=true,PARTY=true,GUILD=true}
        end
    end
    store.migrated04=true
    -- Change untouched v0.6.4 General defaults, but preserve player edits,
    -- non-default tabs, and explicit disabled channel choices.
    if not store.migrated065 then
        local first=store.tabs[1]
        if first and first.name=="General" and first.defaultOn==false
           and type(first.enabled)=="table" then
            local exact=true
            local allowed={["CHANNEL:general"]=true,PARTY=true,GUILD=true}
            local k,v
            for k,v in pairs(first.enabled) do
                if allowed[k]~=v then exact=false end
            end
            for k in pairs(allowed) do
                if first.enabled[k]~=true then exact=false end
            end
            if exact then
                first.enabled.SAY=true;first.enabled.YELL=true
                first.enabled.RAID=true;first.enabled.RAID_WARNING=true
                first.enabled.WHISPER=true;first.enabled.WHISPER_INFORM=true
            end
        end
    end
    store.migrated065=true
    if not store.migrated080 then
        local first=store.tabs[1]
        -- Only update untouched stock General presets. Do not override player
        -- configured channel rules or intentionally excluded channels.
        if first and first.name=="General" and first.defaultOn==false
           and type(first.enabled)=="table" then
            local stock={ ["CHANNEL:general"]=true,PARTY=true,GUILD=true,
                SAY=true,YELL=true,RAID=true,RAID_WARNING=true,
                WHISPER=true,WHISPER_INFORM=true }
            local equal=true
            local k,v
            for k,v in pairs(first.enabled) do
                if stock[k]~=v then equal=false end
            end
            for k,v in pairs(stock) do
                if first.enabled[k]~=v then equal=false end
            end
            if equal then
                first.defaultOn=true
                first.enabled={["CHANNEL:lft"]=false,COMBAT=false}
            end
        end
        local found=false
        local i,t
        for i=1,table.getn(store.tabs) do
            t=store.tabs[i]
            if type(t.name)=="string" and string.lower(t.name)=="combat log" then
                found=true
            end
        end
        if not found and table.getn(store.tabs)<MAX_TABS then
            table.insert(store.tabs,makeCombatTab())
        end
        store.migrated080=true
    end
    cfg=store.settings
    local k,v
    for k,v in pairs(defaults) do
        if cfg[k]==nil or type(cfg[k])~=type(v) then cfg[k]=v end
    end
    if type(cfg.theme)~="table" then cfg.theme={} end
    for k in pairs(paletteDefaults) do
        local color=cfg.theme[k]
        if type(color)=="table" then
            if tonumber(color[1]) and tonumber(color[2]) and tonumber(color[3]) then
                cfg.theme[k]={colorLimit(color[1]),colorLimit(color[2]),colorLimit(color[3])}
            else cfg.theme[k]=nil end
        else cfg.theme[k]=nil end
    end
    cfg.visible=clamp(cfg.visible,1,15)
    cfg.hold=clamp(cfg.hold,1,120)
    cfg.fade=clamp(cfg.fade,1,15)
    cfg.history=clamp(cfg.history,50,MAX_HISTORY)
    cfg.width=clamp(cfg.width,520,900)
    cfg.heightCap=clamp(cfg.heightCap or 0,0,1200)
    cfg.compactHeight=clamp(cfg.compactHeight or 0,0,950)
    cfg.controlsHold=clamp(cfg.controlsHold or 5,0,30)
    cfg.defaultFont=clamp(cfg.defaultFont,9,20)
    if type(cfg.fading)~="boolean" then cfg.fading=true end
    if type(cfg.classColors)~="boolean" then cfg.classColors=true end
    -- Class information is persisted but never inferred from a character name.
    if type(store.playerClasses)~="table" then store.playerClasses={} end
    if MCClassColors then
        store.playerClasses=MCClassColors.Initialize(store.playerClasses)
        MCClassColors.RefreshGuild()
        MCClassColors.RefreshFriends()
    end
    if cfg.clock~="12" and cfg.clock~="24" and cfg.clock~="seconds" then cfg.clock="24" end
    -- Guarantee that a v0.6.1 upgrade starts with the default chat suppressed.
    -- The optional /mchat blizzard on recovery command remains available.
    if not store.nativeDefaultHidden061 then
        cfg.hideBlizzard=true
        store.nativeDefaultHidden061=true
    end
    while table.getn(store.tabs)>MAX_TABS do table.remove(store.tabs) end
    local i,tab,kind,allowed
    for i=1,table.getn(store.tabs) do
        tab=store.tabs[i]
        if type(tab.name)~="string" then tab.name="Tab "..i end
        tab.font=clamp(tab.font or cfg.defaultFont,9,20)
        if type(tab.enabled)~="table" then tab.enabled={} end
        if type(tab.colors)~="table" then tab.colors={} end
        if type(tab.defaultOn)~="boolean" then tab.defaultOn=true end
        if type(tab.phrases)~="table" then tab.phrases={} end
        if type(tab.useWCF)~="boolean" then tab.useWCF=true end
        if type(tab.filterEnabled)~="boolean" then tab.filterEnabled=true end
        if type(tab.worldOnly)~="boolean" then tab.worldOnly=true end
        if type(tab.adSensitivity)~="string" then tab.adSensitivity="balanced" end
        if type(tab.adCategories)~="table" then tab.adCategories={} end
        -- Existing Combat Log tabs get mini-tabs, including renamed stock
        -- combat tabs that contain only the COMBAT channel.
        if tab.isCombatTab==nil then
            local onlyCombat=tab.enabled.COMBAT==true and not tab.defaultOn
            for kind,allowed in pairs(tab.enabled) do
                if kind~="COMBAT" and allowed then onlyCombat=false end
            end
            if onlyCombat or (tab.name=="Combat Log" and tab.enabled.COMBAT) then
                tab.isCombatTab=true
            end
        end
        if tab.isCombatTab and tab.combatView~="all" and tab.combatView~="me" then
            tab.combatView="all"
        end
    end
    cfg.selected=clamp(cfg.selected,1,table.getn(store.tabs))
    -- Migration: v0.1.0 saved rendered messages without a channel/type. Keep
    -- them readable in every tab, but they cannot be re-filtered or recolored.
    for i=1,table.getn(store.entries) do
        local r=store.entries[i]
        if type(r)=="table" and not r.kind and r.text then r.legacy=true end
    end
    MCHistory.Initialize(store,cfg.history)
    discoverChannels()
    nativeParking=CreateFrame("Frame","MicrochipChatNativeChatParking",UIParent)
    nativeParking:Hide()
    createUI()
    editBox=getglobal("ChatFrameEditBox")
    if editBox and editBox:GetParent()~=UIParent then editBox:SetParent(UIParent) end
    initialized=true
    updateAll(true,true)
    setExpanded(false)
    suppressNative()
    MicrochipChat_InitializeDetachedWindows()
    updateAll(true,true)
    inputPosition()
    for k in pairs(eventKinds) do controller:RegisterEvent(k) end
    local ci
    -- Some modified clients omit individual old combat events. Skip those
    -- without aborting startup or revealing the suppressed Blizzard chat.
    for ci=1,table.getn(combatEvents) do
        pcall(controller.RegisterEvent,controller,combatEvents[ci])
    end
    controller:RegisterEvent("PLAYER_ENTERING_WORLD")
    controller:RegisterEvent("CHANNEL_UI_UPDATE")
    -- Class lookups come from native rosters/units and never auto-send /who.
    local cevents={"PLAYER_TARGET_CHANGED","UPDATE_MOUSEOVER_UNIT", "PARTY_MEMBERS_CHANGED",
        "RAID_ROSTER_UPDATE","GUILD_ROSTER_UPDATE","FRIENDLIST_UPDATE","WHO_LIST_UPDATE"}
    for ci=1,table.getn(cevents) do
        pcall(controller.RegisterEvent,controller,cevents[ci])
    end
    controlsLastHover=GetTime()

    -- Settings are intentionally optional to the core chat startup.  A missing
    -- client method or incompatible UI template in the settings panel can no
    -- longer interrupt chat capture and leave the Blizzard frame showing.
    local ok, err=pcall(createSettingsUi)
    if not ok then
        settingsError=tostring(err or "unknown error")
        if S.settingsFrame then S.settingsFrame:Hide() end
        S.settingsFrame=nil
        settingsOpen=false
        if UIErrorsFrame and UIErrorsFrame.AddMessage then
            UIErrorsFrame:AddMessage("Microchip-chat: settings failed; chat is active. /mchat help",1,0.2,0.2)
        end
        notify("Settings failed: "..string.sub(settingsError,1,180))
    else
        settingsError=nil
        notify("v0.9.0 loaded. Class-colored player names: "..(cfg.classColors and "ON" or "OFF")..".")
    end
    suppressNative()
end

controller:SetScript("OnEvent",function()
    if event=="PLAYER_LOGIN" then
        startup()
    elseif not initialized then
        return
    elseif event=="PLAYER_ENTERING_WORLD" then
        discoverChannels(); suppressNative(); inputPosition()
        if MCClassColors and MCClassColors.RefreshUnits() and cfg.classColors then
            paintLive()
            if expanded then paintHistory() end
        end
    elseif event=="CHANNEL_UI_UPDATE" then
        discoverChannels()
        if settingsOpen then refreshSettingsRows() end
    elseif event=="PLAYER_TARGET_CHANGED" or event=="UPDATE_MOUSEOVER_UNIT" or
           event=="PARTY_MEMBERS_CHANGED" or event=="RAID_ROSTER_UPDATE" or
           event=="GUILD_ROSTER_UPDATE" or event=="FRIENDLIST_UPDATE" or
           event=="WHO_LIST_UPDATE" then
        if MCClassColors then
            local changed=false
            if event=="GUILD_ROSTER_UPDATE" then changed=MCClassColors.RefreshGuild()
            elseif event=="FRIENDLIST_UPDATE" then changed=MCClassColors.RefreshFriends()
            elseif event=="WHO_LIST_UPDATE" then changed=MCClassColors.RefreshWho()
            else changed=MCClassColors.RefreshUnits() end
            if changed and cfg.classColors then
                paintLive()
                if expanded then paintHistory() end
            end
        end
    else
        if event=="CHAT_MSG_SYSTEM" and MCClassColors then
            local changed=MCClassColors.RefreshWho()
            if MCClassColors.RefreshPrat() then changed=true end
            if changed and cfg.classColors then
                paintLive()
                if expanded then paintHistory() end
            end
        end
        local kind=eventKinds[event]
        if not kind and (string.sub(event,1,16)=="CHAT_MSG_COMBAT_" or
                         string.sub(event,1,15)=="CHAT_MSG_SPELL_") then
            kind="COMBAT"
        end
        if kind then
            local channelName,channelNumber
            if kind=="CHANNEL" then
                channelName=arg9
                if not channelName or channelName=="" then channelName=arg4 end
                channelNumber=tonumber(arg8)
            end
            append(kind,arg1,arg2,channelName,channelNumber,nil,arg4,arg7,
                   kind=="COMBAT" and event or nil)
        end
    end
end)
controller:RegisterEvent("PLAYER_LOGIN")
controller:SetScript("OnUpdate",function()
    if not initialized then return end
    -- Dim only the bottom toolbar and tabs. Keep both mouse-responsive while
    -- dimmed so a hover immediately restores them, without a new click.
    if root and root.controlStrip and root.controlDock then
        local hovered=false
        if MouseIsOver then
            hovered=MouseIsOver(root.controlStrip) or MouseIsOver(root.controlDock)
        elseif GetCursorPosition then
            local x,y=GetCursorPosition()
            local scale=root:GetEffectiveScale() or 1
            x=x/scale;y=y/scale
            local left,right=root:GetLeft(),root:GetRight()
            local bottom=root:GetBottom()
            hovered=left and right and bottom and x>=left and x<=right and
                    y>=bottom and y<=bottom+58
        end
        if hovered then controlsLastHover=GetTime() end
        local show=(GetTime()-controlsLastHover)<cfg.controlsHold or hovered or settingsOpen or resizing
        local target=show and 1 or 0
        local speed=(arg1 or 0)*2.8
        if controlsAlpha<target then controlsAlpha=math.min(target,controlsAlpha+speed)
        else controlsAlpha=math.max(target,controlsAlpha-speed) end
        if controlsPaintedAlpha~=controlsAlpha then
            local i
            for i=1,table.getn(controlVisuals) do
                controlVisuals[i]:SetAlpha(controlsAlpha)
            end
            controlsPaintedAlpha=controlsAlpha
        end
    end
    updateTimer=updateTimer+arg1
    if updateTimer<0.6 then return end
    updateTimer=0
    suppressNative()
    inputPosition()
    if expanded and not resizing then updateSize() end
end)

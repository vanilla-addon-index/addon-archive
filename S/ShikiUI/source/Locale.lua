function SUI.SetLocale(code)
	if code == "auto" then
		code = (GetLocale and GetLocale() == "frFR") and "fr" or "en"
	end
	if not SUI.locales[code] then code = "fr" end
	SUI.locale = code
end

-- L(cle, a, b, c, d) : texte traduit, repli sur le francais puis sur la cle (la cle manquante est memorisee).
function SUI.L(key, a, b, c, d)
	local s = SUI.locales[SUI.locale][key]
	if s == nil then s = SUI.locales.fr[key] end
	if s == nil then
		SUI.missingL[key] = true
		return key
	end
	if a ~= nil then return string.format(s, a, b, c, d) end
	return s
end

-- AddStrings(code, tbl) : ajoute les textes d'un fichier Locale_<Module>.lua (un par module, jamais de modification de Locale.lua).
-- Ne remplace JAMAIS une cle deja presente (noyau ou autre module) : les cles ignorees sont comptees et memorisees dans
-- SUI.localeSkipped (cle "fr:ma.cle") pour que les tests les signalent. Retourne ajoutees, ignorees.
SUI.localeSkipped = {}
function SUI.AddStrings(code, tbl)
	local dest = SUI.locales[code]
	if type(dest) ~= "table" or type(tbl) ~= "table" then return 0, 0 end
	local added, skipped = 0, 0
	for k, v in pairs(tbl) do
		if type(k) ~= "string" or type(v) ~= "string" or dest[k] ~= nil then
			skipped = skipped + 1
			if type(k) == "string" then SUI.localeSkipped[code .. ":" .. k] = true end
		else
			dest[k] = v
			SUI.missingL[k] = nil
			added = added + 1
		end
	end
	return added, skipped
end
